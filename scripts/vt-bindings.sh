#!/bin/sh
# Regenerates ternd's bindings to libghostty-vt from vendor/ghostty's headers.
# Run after bumping the Ghostty submodule. Needs bindgen (cargo install bindgen-cli).
set -e
cd "$(dirname "$0")/.."
bindgen vendor/ghostty/include/ghostty/vt.h \
  --allowlist-function 'ghostty_terminal_(new|free|vt_write|resize|set|get)' \
  --allowlist-function 'ghostty_formatter_(terminal_new|format|free)' \
  --allowlist-type 'GhosttyTerminalScreen|GhosttyString' \
  --no-prepend-enum-name \
  --allowlist-type 'GhosttyTerminal(TitleChanged|Bell|WritePty|ProgramStatus|SemanticPrompt)Fn' \
  --no-layout-tests --no-doc-comments \
  --raw-line '// Generated by scripts/vt-bindings.sh; do not edit.' \
  --raw-line '#![allow(non_upper_case_globals, non_camel_case_types, non_snake_case, dead_code)]' \
  -o crates/tern/src/bin/ternd/vt/ffi.rs \
  -- -Ivendor/ghostty/include
echo "wrote crates/tern/src/bin/ternd/vt/ffi.rs"
